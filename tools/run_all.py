def main():
    fails = []
    for uid, (name, look) in UNITS.items():
        out = Path(f"out/sprites_raw/{uid}.png")
        if out.exists():
            print(f"skip {uid} (exists)", flush=True)
            continue
        prop = JOB_PROP.get(None, "")
        # 职业道具从 UNITS 元组外查：这里用 demo 的职业映射
