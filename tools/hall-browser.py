"""Unified hall acceptance checks in isolated Chromium. Run from project root."""
import json
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

BASE='http://127.0.0.1:8086'
OUT=Path('out/hall')
OUT.mkdir(parents=True,exist_ok=True)
checks=[]
def check(value,label):
    assert value,label
    checks.append(label)

with sync_playwright() as p:
    browser=p.chromium.launch()
    for width,height in [(1440,1000),(768,1024),(390,844),(320,740)]:
        ctx=browser.new_context(viewport={'width':width,'height':height})
        page=ctx.new_page()
        errors=[]
        failed=[]
        page.on('pageerror',lambda e:errors.append(str(e)))
        page.on('response',lambda r:failed.append(r.url) if r.status>=400 else None)
        page.goto(BASE+'/')
        expect(page.locator('.game-card')).to_have_count(8)
        expect(page.locator('.upcoming-item')).to_have_count(6)
        check(page.locator('.upcoming-item a').count()==0,f'{width}: planned games have no launch links')
        page.wait_for_function('Array.from(document.images).every(i=>i.complete)')
        check(page.evaluate('Array.from(document.images).every(i=>i.naturalWidth>0)'),f'{width}: all images load')
        check(page.evaluate('document.documentElement.scrollWidth<=innerWidth'),f'{width}: no horizontal overflow')
        page.screenshot(path=str(OUT/f'hall-{width}.png'),full_page=True)
        page.screenshot(path=str(OUT/f'first-screen-{width}.png'))
        page.locator('#search').fill('岁己 工作室')
        expect(page.locator('.game-card')).to_have_count(1)
        expect(page.locator('.game-card h3')).to_have_text('今晚谁来播')
        page.locator('#search').fill('无此游戏')
        expect(page.locator('.empty')).to_be_visible()
        page.locator('#reset-filters').click()
        page.locator('[data-category="策略对战"]').click()
        expect(page.locator('.game-card')).to_have_count(3)
        page.locator('[data-category=all]').click()
        check(True,f'{width}: character search, empty recovery and category filters work')
        page.locator('[data-favorite=studio-manager]').click()
        page.reload()
        expect(page.locator('[data-favorite=studio-manager]')).to_have_attribute('aria-pressed','true')
        page.locator('[data-tab=favorites]').click()
        expect(page.locator('.game-card')).to_have_count(1)
        page.locator('[data-favorite=studio-manager]').click()
        expect(page.locator('.empty')).to_be_visible()
        page.locator('#reset-filters').click()
        check(True,f'{width}: favorites persist and can be removed')
        fixtures={k:'hall-fixture-'+k for k in ['vc_save4','vc_daily3','vc_arena3','star_survivor_v1','astral_princess_rpg_v1']}
        page.evaluate('(items)=>{for(const[k,v]of Object.entries(items))localStorage.setItem(k,v)}',fixtures)
        page.locator('.play-link[data-game=studio-manager]').click()
        expect(page.locator('[data-action=start]')).to_be_enabled()
        page.locator('.brand').click()
        expect(page.locator('.game-card')).to_have_count(8)
        page.locator('[data-tab=recent]').click()
        expect(page.locator('.game-card')).to_have_count(1)
        check(page.evaluate('(keys)=>Object.fromEntries(keys.map(k=>[k,localStorage.getItem(k)]))',list(fixtures))==fixtures,f'{width}: navigation records recents and preserves legacy save fixtures')
        check(not errors,f'{width}: no page errors')
        check(not failed,f'{width}: no HTTP errors')
        ctx.close()
    # Every old entry opens in a clean profile; this checks entry readiness, not combat balance.
    for entry,selector in [('/classic.html','#flowHome'),('/arena.html','#homeArena'),('/online.html','#entryScreen'),('/survival.html','#start'),('/rpg/','#startChapter'),('/rpg/action.html','#startBtn')]:
        ctx=browser.new_context(viewport={'width':1440,'height':900})
        page=ctx.new_page()
        page.goto(BASE+entry)
        expect(page.locator(selector)).to_be_visible(timeout=20000)
        check(True,f'{entry}: legacy launch UI ready')
        ctx.close()
    ctx=browser.new_context()
    page=ctx.new_page();page.goto(BASE+'/')
    expect(page.locator('.game-card')).to_have_count(8)
    page.evaluate('navigator.serviceWorker.ready')
    page.wait_for_function('navigator.serviceWorker.controller!==null')
    ctx.set_offline(True)
    page.reload()
    expect(page.locator('.game-card')).to_have_count(8)
    page.locator('.play-link[data-game=classic]').click()
    expect(page.locator('#flowHome')).to_be_visible()
    check(True,'Installed cache: offline root still lists eight games and classic entry launches')
    ctx.close()
    ctx=browser.new_context()
    ctx.add_init_script("Object.defineProperty(window,'localStorage',{get(){throw new DOMException('blocked','SecurityError')}})")
    page=ctx.new_page();page.goto(BASE+'/library/')
    expect(page.locator('.game-card')).to_have_count(8)
    page.locator('[data-favorite=classic]').click()
    expect(page.locator('#preference-note')).to_be_visible()
    check(True,'Blocked localStorage: library alias and in-memory favorites still work')
    ctx.close()
    browser.close()
(OUT/'browser-results.json').write_text(json.dumps(checks,ensure_ascii=False,indent=2),encoding='utf8')
print(f'{len(checks)} hall browser checks passed')
